NO_CONTEXT_ANSWER = "根据现有资料无法回答这个问题——知识库中没有检索到相关依据。"


def build_rag_user_message(question: str, contexts: list[str]) -> str:
    """把检索到的资料和问题拼成一条用户消息。"""
    blocks = "\n\n".join(
        f"[{i}] {ctx}" for i, ctx in enumerate(contexts, start=1)
    )
    return (
        "参考资料：\n"
        f"{blocks}\n\n"
        "----\n"
        f"问题：{question}\n\n"
        "请严格依据上面的参考资料回答，并用 [编号] 标注来源。"
    )
